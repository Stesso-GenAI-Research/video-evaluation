"""Generate deterministic, explicitly synthetic preference-evaluation inputs.

The generated labels are useful for exercising the pipeline and preparing
later analysis code.  They are target-derived pseudo-judgments, not human or
Stesso judgments and must never be presented as research evidence.
"""

from __future__ import annotations

import json
import random
from collections import defaultdict
from pathlib import Path
from typing import Any, Final

from action_semantics.config import DEFAULT_RANDOM_SEED
from action_semantics.io_utils import read_clips, write_csv, write_jsonl
from action_semantics.models import ClipRecord
from action_semantics.provenance import build_manifest
from action_semantics.retrieval.clip_resolution import clip_interval
from action_semantics.retrieval.preference_evaluation import prepare_preference_index
from action_semantics.text import normalize_text


SYNTHETIC_GENERATOR_VERSION: Final[str] = "target-derived-preferences-v1"
DEFAULT_SYNTHETIC_STEP_COUNT: Final[int] = 40
SYNTHETIC_CONFIDENCE: Final[float] = 0.5


def _inventory(clip: ClipRecord, key: str) -> list[str]:
    metadata = clip.gemini_metadata.get("clip", {})
    if not isinstance(metadata, dict):
        return []
    values = metadata.get(key, [])
    if not isinstance(values, list):
        return []
    output: list[str] = []
    seen: set[str] = set()
    for value in values:
        if not isinstance(value, str):
            continue
        normalized = normalize_text(value)
        if normalized and normalized.casefold() not in seen:
            output.append(normalized)
            seen.add(normalized.casefold())
    return output


def _category_name(clip: ClipRecord) -> str | None:
    source_video = clip.gemini_metadata.get("source_video", {})
    if not isinstance(source_video, dict):
        return None
    category = source_video.get("category")
    if isinstance(category, dict):
        value = category.get("name")
    else:
        value = category
    normalized = normalize_text(value)
    return normalized or None


def _eligible_clip(clip: ClipRecord) -> bool:
    start, end = clip_interval(clip)
    return bool(
        clip.video_id is not None
        and normalize_text(clip.title)
        and normalize_text(clip.description or clip.summary)
        and start is not None
        and end is not None
        and end > start
    )


def _timestamp_reference(clip: ClipRecord) -> dict[str, Any]:
    start, end = clip_interval(clip)
    if clip.video_id is None or start is None or end is None:
        raise ValueError(f"Clip lacks a resolvable timestamp reference: {clip.clip_id}")
    return {
        "video_id": str(clip.video_id),
        "start_seconds": start,
        "end_seconds": end,
    }


def _clip_audit_fields(prefix: str, clip: ClipRecord) -> dict[str, Any]:
    start, end = clip_interval(clip)
    return {
        f"{prefix}_clip_id": clip.clip_id,
        f"{prefix}_video_id": clip.video_id,
        f"{prefix}_start_seconds": start,
        f"{prefix}_end_seconds": end,
        f"{prefix}_title": clip.title,
    }


def _write_notice(path: Path, *, step_count: int, pair_count: int, seed: int) -> None:
    text = f"""# Synthetic preference development data

These files were generated by `{SYNTHETIC_GENERATOR_VERSION}` for pipeline
development. They contain {step_count} target-derived steps and {pair_count}
fabricated A/B pseudo-judgments (seed {seed}).

They are **not** Stesso W25 labels, human judgments, cascade output, or research
evidence. The synthetic winner is always the canonical clip whose metadata was
used to construct the step. This creates intentional answer leakage and makes
agreement rates unsuitable for any scientific conclusion.

Files:

- `steps.jsonl`: deterministic synthetic steps derived from target clips.
- `pairwise.jsonl`: two pseudo-judgments per step, one within-video and one
  cross-video distractor, with balanced A/B winner positions.
- `pair_audit.csv`: readable titles, timestamps, pair type, and winner rationale.
- `generation_manifest.json`: source hashes and generator parameters.

Use these files to exercise Step 1 and prepare downstream code only. Replace
them with the real W25 export before reporting results.
"""
    path.write_text(text, encoding="utf-8")


def generate_synthetic_preferences(
    *,
    index: Path,
    output_dir: Path,
    step_count: int = DEFAULT_SYNTHETIC_STEP_COUNT,
    seed: int = DEFAULT_RANDOM_SEED,
    overwrite: bool = False,
) -> dict[str, Path]:
    """Create deterministic target-derived steps and pairwise pseudo-labels."""
    if step_count < 2:
        raise ValueError("step_count must be at least 2")
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "steps": output_dir / "steps.jsonl",
        "pairs": output_dir / "pairwise.jsonl",
        "audit": output_dir / "pair_audit.csv",
        "notice": output_dir / "DATA_NOTICE.md",
        "manifest": output_dir / "generation_manifest.json",
    }
    existing = [str(path) for path in paths.values() if path.exists()]
    if existing and not overwrite:
        raise ValueError(
            "Refusing to overwrite synthetic preference artifacts: "
            + ", ".join(existing)
        )

    index_artifacts = prepare_preference_index(index, output_dir)
    clips = [clip for clip in read_clips(index_artifacts.clips_jsonl) if _eligible_clip(clip)]
    by_video: defaultdict[str, list[ClipRecord]] = defaultdict(list)
    for clip in clips:
        by_video[str(clip.video_id)].append(clip)
    for video_clips in by_video.values():
        video_clips.sort(
            key=lambda clip: (
                clip_interval(clip)[0] or 0.0,
                clip_interval(clip)[1] or 0.0,
                clip.clip_id,
            )
        )
    eligible_videos = sorted(
        video_id for video_id, video_clips in by_video.items() if len(video_clips) >= 2
    )
    if len(eligible_videos) < step_count:
        raise ValueError(
            f"Requested {step_count} synthetic steps, but only "
            f"{len(eligible_videos)} videos contain two eligible clips"
        )

    rng = random.Random(seed)
    rng.shuffle(eligible_videos)
    selected_video_ids = eligible_videos[:step_count]
    targets: list[ClipRecord] = []
    within_distractors: list[ClipRecord] = []
    for video_id in selected_video_ids:
        video_clips = by_video[video_id]
        target_index = rng.randrange(len(video_clips))
        targets.append(video_clips[target_index])
        within_distractors.append(video_clips[(target_index + 1) % len(video_clips)])

    step_rows: list[dict[str, Any]] = []
    pair_rows: list[dict[str, Any]] = []
    audit_rows: list[dict[str, Any]] = []
    for step_index, (target, within_distractor) in enumerate(
        zip(targets, within_distractors, strict=True), start=1
    ):
        step_id = f"synthetic-development-step-{step_index:03d}"
        step_rows.append(
            {
                "id": step_id,
                "title": normalize_text(target.title),
                "description": normalize_text(target.description or target.summary),
                "tools": _inventory(target, "tools"),
                "materials": _inventory(target, "supplies"),
                "synthetic": True,
                "synthetic_generator": SYNTHETIC_GENERATOR_VERSION,
                "synthetic_target_clip_id": target.clip_id,
                "synthetic_source_category": _category_name(target),
            }
        )
        cross_distractor = targets[step_index % len(targets)]
        pair_specs = (
            (
                "within-video",
                within_distractor,
                _timestamp_reference(target),
                {"clip_id": within_distractor.clip_id},
                "synthetic_within_video_target_rule_v1",
            ),
            (
                "cross-video",
                cross_distractor,
                {"clip_id": target.clip_id},
                _timestamp_reference(cross_distractor),
                "synthetic_cross_video_target_rule_v1",
            ),
        )
        for pair_offset, (
            pair_type,
            distractor,
            target_reference,
            distractor_reference,
            provenance,
        ) in enumerate(pair_specs):
            pair_number = (step_index - 1) * len(pair_specs) + pair_offset + 1
            winner_position = "A" if (step_index + pair_offset) % 2 else "B"
            if winner_position == "A":
                clip_a_reference = target_reference
                clip_b_reference = distractor_reference
                clip_a = target
                clip_b = distractor
            else:
                clip_a_reference = distractor_reference
                clip_b_reference = target_reference
                clip_a = distractor
                clip_b = target
            comparison_id = f"synthetic-development-pair-{pair_number:03d}"
            rationale = (
                "Fabricated label: the winner is the target clip whose metadata "
                "was copied into the synthetic step."
            )
            pair_rows.append(
                {
                    "comparison_id": comparison_id,
                    "step_id": step_id,
                    "clip_a": clip_a_reference,
                    "clip_b": clip_b_reference,
                    "winner_position": winner_position,
                    "winner_clip_id": target.clip_id,
                    "judge_provenance": provenance,
                    "judge_confidence": SYNTHETIC_CONFIDENCE,
                    "judge_id": SYNTHETIC_GENERATOR_VERSION,
                    "synthetic": True,
                    "synthetic_pair_type": pair_type,
                    "synthetic_label_rationale": rationale,
                }
            )
            audit_rows.append(
                {
                    "comparison_id": comparison_id,
                    "step_id": step_id,
                    "step_title": target.title,
                    "pair_type": pair_type,
                    **_clip_audit_fields("clip_a", clip_a),
                    **_clip_audit_fields("clip_b", clip_b),
                    "winner_position": winner_position,
                    "winner_clip_id": target.clip_id,
                    "judge_provenance": provenance,
                    "judge_confidence": SYNTHETIC_CONFIDENCE,
                    "synthetic_label_rationale": rationale,
                }
            )

    write_jsonl(paths["steps"], step_rows)
    write_jsonl(paths["pairs"], pair_rows)
    write_csv(paths["audit"], audit_rows)
    _write_notice(
        paths["notice"], step_count=len(step_rows), pair_count=len(pair_rows), seed=seed
    )
    manifest = build_manifest(
        command="generate-synthetic-pairs",
        input_files=[index_artifacts.clips_jsonl],
        output_files=[paths["steps"], paths["pairs"], paths["audit"], paths["notice"]],
        parameters={
            "generator_version": SYNTHETIC_GENERATOR_VERSION,
            "synthetic": True,
            "research_evidence": False,
            "seed": seed,
            "step_count": len(step_rows),
            "pairs_per_step": 2,
            "pair_count": len(pair_rows),
            "winner_position_policy": "alternating A/B",
            "label_rule": "target clip used to construct each synthetic step wins",
            "judge_confidence": SYNTHETIC_CONFIDENCE,
            "index_root": str(index_artifacts.root),
        },
    )
    manifest["schema_version"] = "synthetic-preference-generation.v1"
    paths["manifest"].write_text(
        json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return {**paths, "index_root": index_artifacts.root}
